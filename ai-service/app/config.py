import os

from dotenv import load_dotenv


# ============================================================
# LOAD ENVIRONMENT VARIABLES
# ============================================================

load_dotenv()


# ============================================================
# SETTINGS
# ============================================================

class Settings:

    # --------------------------------------------------------
    # Application
    # --------------------------------------------------------

    app_name: str = os.getenv(
        "APP_NAME",
        "DevFlow X AI Service"
    )

    app_env: str = os.getenv(
        "APP_ENV",
        "development"
    )


    # --------------------------------------------------------
    # Server
    # --------------------------------------------------------

    port: int = int(
        os.getenv(
            "PORT",
            os.getenv(
                "AI_SERVICE_PORT",
                "8000"
            )
        )
    )


    # --------------------------------------------------------
    # Groq
    # --------------------------------------------------------

    groq_api_key: str = os.getenv(
        "GROQ_API_KEY",
        ""
    )

    groq_model: str = os.getenv(
        "GROQ_MODEL",
        "openai/gpt-oss-120b"
    )


    # --------------------------------------------------------
    # Frontend
    # --------------------------------------------------------

    frontend_url: str = os.getenv(
        "FRONTEND_URL",
        "http://localhost:5173"
    )


# ============================================================
# SETTINGS INSTANCE
# ============================================================

settings = Settings()
